#!/usr/bin/env python3
"""Validate fonts.json, normalise its formatting, and regenerate the README catalog.

Usage:
  python3 scripts/build.py          validate, reformat fonts.json, rewrite README
  python3 scripts/build.py --check  validate only; fail if fonts.json or README is out of date

Standard library only.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "fonts.json"
README = ROOT / "README.md"
START = "<!-- catalog:start (generated by scripts/build.py, do not edit) -->"
END = "<!-- catalog:end -->"

REQUIRED = {
    "id": str, "name": str, "category": str, "by": str, "license": str, "url": str,
    "feel": list, "use": list, "note": str, "variable": bool, "weights": list,
    "italics": bool, "scripts": list,
}
OPTIONAL = {"caveats": (str, type(None)), "review": bool}
SCRIPTS = {"latin", "cyrillic", "greek", "vietnamese", "hebrew", "arabic", "devanagari"}


def validate(data):
    errors = []
    vocab = data["vocab"]
    feels, uses = set(vocab["feel"]), set(vocab["use"])
    categories, licenses = set(vocab["category"]), set(vocab["license"])
    ids = set()

    for i, f in enumerate(data["fonts"]):
        where = f.get("id", f"fonts[{i}]")
        broken = False
        for key, typ in REQUIRED.items():
            if key not in f:
                errors.append(f"{where}: missing '{key}'")
                broken = True
            elif not isinstance(f[key], typ):
                errors.append(f"{where}: '{key}' should be {typ.__name__}")
                broken = True
        for key in f:
            if key not in REQUIRED and key not in OPTIONAL:
                errors.append(f"{where}: unknown field '{key}'")
        for key, typ in OPTIONAL.items():
            if key in f and not isinstance(f[key], typ):
                errors.append(f"{where}: '{key}' has the wrong type")
        if broken:
            # Still register the id so avoid-list references don't cascade into false errors.
            if isinstance(f.get("id"), str):
                ids.add(f["id"])
            continue

        if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", f["id"]):
            errors.append(f"{where}: id must be kebab-case")
        if f["id"] in ids:
            errors.append(f"{where}: duplicate id")
        ids.add(f["id"])
        if f["category"] not in categories:
            errors.append(f"{where}: category '{f['category']}' not in {sorted(categories)}")
        if f["license"] not in licenses:
            errors.append(f"{where}: license '{f['license']}' not in {sorted(licenses)}")
        for key, allowed in (("feel", feels), ("use", uses)):
            tags = f[key]
            if not 1 <= len(tags) <= 3:
                errors.append(f"{where}: '{key}' needs 1-3 tags, has {len(tags)}")
            if len(set(tags)) != len(tags):
                errors.append(f"{where}: duplicate '{key}' tags")
            for t in tags:
                if t not in allowed:
                    errors.append(f"{where}: '{key}' tag '{t}' not in vocab")
        if not f["weights"] or f["weights"] != sorted(set(f["weights"])):
            errors.append(f"{where}: weights must be a sorted, non-empty list")
        for s in f["scripts"]:
            if s not in SCRIPTS:
                errors.append(f"{where}: script '{s}' not in {sorted(SCRIPTS)}")
        if "fonts.googleapis.com" in f["url"] or "api.fontshare.com" in f["url"]:
            errors.append(f"{where}: url must be a source page, not a CDN")

    avoid_keys = {"name", "why", "instead", "ai_rate", "google_rank", "measured"}
    for a in data["avoid"]:
        for key in set(a) - avoid_keys:
            errors.append(f"avoid '{a.get('name')}': unknown field '{key}'")
        for target in a["instead"]:
            if target not in ids:
                errors.append(f"avoid '{a['name']}': unknown font id '{target}'")
    return errors


def dump(data):
    """JSON with scalar-only lists on one line, so diffs stay readable."""
    text = json.dumps(data, indent=2, ensure_ascii=False)
    def collapse(m):
        items = [x.strip() for x in m.group(1).split(",")]
        return "[" + ", ".join(items) + "]"
    text = re.sub(r"\[\s*((?:(?:\"[^\"\n]*\"|-?\d+|true|false|null)\s*,\s*)*(?:\"[^\"\n]*\"|-?\d+|true|false|null))\s*\]",
                  collapse, text)
    return text + "\n"


def weights_label(ws):
    return f"{ws[0]}" if len(ws) == 1 else f"{ws[0]}–{ws[-1]}"


def font_line(f):
    flags = []
    if f["license"] == "FFL":
        flags.append("FFL")
    if not f["italics"]:
        flags.append("no italics")
    if f.get("review"):
        flags.append("unreviewed")
    extra = f" ({', '.join(flags)})" if flags else ""
    return f"- [{f['name']}]({f['url']}): *{f['category']}*, {', '.join(f['feel'])}{extra}. {f['note']}"


def catalog(data):
    fonts, vocab = data["fonts"], data["vocab"]
    out = []

    out.append("## By use\n")
    out.append("Fonts whose *primary* use is the job are listed first.\n")
    for use, meaning in vocab["use"].items():
        hits = [f for f in fonts if use in f["use"]]
        hits.sort(key=lambda f: f["use"].index(use))
        out.append(f"### {use}\n\n{meaning}.\n")
        out += [font_line(f) for f in hits]
        out.append("")

    out.append("## By feel\n")
    for feel, meaning in vocab["feel"].items():
        hits = [f for f in fonts if feel in f["feel"]]
        hits.sort(key=lambda f: f["feel"].index(feel))
        out.append(f"### {feel}\n\n{meaning}.\n")
        out += [f"- [{f['name']}]({f['url']}): *{f['category']}*, for {', '.join(f['use'])}" for f in hits]
        out.append("")

    out.append("## All fonts\n")
    out.append("| Font | Category | Feel | Use | Weights | Italics | Scripts | License |")
    out.append("|---|---|---|---|---|---|---|---|")
    for f in fonts:
        name = f"[{f['name']}]({f['url']})" + (" ⚠︎" if f.get("review") else "")
        out.append(
            f"| {name} | {f['category']} | {', '.join(f['feel'])} | {', '.join(f['use'])} | "
            f"{weights_label(f['weights'])}{' var' if f['variable'] else ''} | {'yes' if f['italics'] else 'no'} | "
            f"{', '.join(f['scripts'])} | {f['license']} |"
        )
    out.append("\n⚠︎ = tags not yet reviewed by a human.\n")

    out.append("## Avoid as defaults\n")
    names = {f["id"]: f["name"] for f in fonts}
    for a in data["avoid"]:
        evidence = ""
        if a.get("measured"):
            rank = f"Google #{a['google_rank']}" if a.get("google_rank") else "not on Google"
            ai = f"AI rate {a['ai_rate']:.0%}" if a.get("ai_rate") is not None else "AI rate not measured"
            evidence = f" *({ai}, {rank}, measured {a['measured']})*"
        out.append(f"- **{a['name']}**: {a['why']} Try {', '.join(names[i] for i in a['instead'])}.{evidence}")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv
    raw = FONTS.read_text()
    data = json.loads(raw)

    errors = validate(data)
    if errors:
        print("✗ fonts.json is invalid:", *errors, sep="\n  ", file=sys.stderr)
        sys.exit(1)

    readme = README.read_text()
    if START not in readme or END not in readme:
        print(f"✗ README.md is missing the catalog markers", file=sys.stderr)
        sys.exit(1)
    head, rest = readme.split(START, 1)
    tail = rest.split(END, 1)[1]
    new_readme = f"{head}{START}\n\n{catalog(data)}\n{END}{tail}"
    new_raw = dump(data)

    if check:
        stale = [p.name for p, old, new in ((FONTS, raw, new_raw), (README, readme, new_readme)) if old != new]
        if stale:
            print(f"✗ Out of date: {', '.join(stale)}. Run python3 scripts/build.py", file=sys.stderr)
            sys.exit(1)
    else:
        FONTS.write_text(new_raw)
        README.write_text(new_readme)

    review = sum(1 for f in data["fonts"] if f.get("review"))
    print(f"✓ {len(data['fonts'])} fonts valid ({review} awaiting review)")


if __name__ == "__main__":
    main()
